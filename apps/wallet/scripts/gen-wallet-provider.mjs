#!/usr/bin/env node
/**
 * Build-time step: converts the demo wallet provider's PKCS#8 key (packages/wallet-core/test/fixtures/wallet-provider)
 * into a private JWK plus its x5c and writes src/config/walletProvider.generated.ts.
 *
 * DEMO ONLY: this puts the wallet provider's private signing key into the app bundle, so anyone can mint wallet and
 * key attestations with it. A real wallet obtains attestations from its wallet provider backend instead.
 */
import { createPrivateKey } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', '..', '..', 'packages', 'wallet-core', 'test', 'fixtures', 'wallet-provider');
const pemBody = (p) => readFileSync(join(dir, p), 'utf8').replace(/-----[^-]+-----/g, '').replace(/\s/g, '');

const jwk = createPrivateKey(readFileSync(join(dir, 'wp-signer.key'))).export({ format: 'jwk' });
const out = join(here, '..', 'src', 'config', 'walletProvider.generated.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `/* eslint-disable */
// GENERATED by scripts/gen-wallet-provider.mjs from packages/wallet-core/test/fixtures/wallet-provider. Do not edit.
// DEMO ONLY: the wallet provider's PRIVATE signing key is embedded in the app bundle. This is acceptable for a throwaway
// demo wallet; a production wallet gets wallet/key attestations from its wallet provider backend and never ships this key.
export const WALLET_PROVIDER_SIGNER_JWK = ${JSON.stringify({ kty: jwk.kty, crv: jwk.crv, x: jwk.x, y: jwk.y, d: jwk.d })} as const;
export const WALLET_PROVIDER_X5C: string[] = ${JSON.stringify([pemBody('wp-signer.pem')])};
`);
console.log(`wrote ${out}`);
